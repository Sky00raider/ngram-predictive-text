"""Load Project 2 (malayalam-gpt) read-only: its model code, tokenizer, checkpoint and val split.

Both projects keep their code in a package called `src`, so importing P2 as
`src` would clash with this project. Instead P2's `src/` package is loaded
under the alias `p2`; its relative imports (`from .config import Config`)
then resolve inside `p2`. Nothing in ../malayalam-gpt is written to.
"""
import importlib
import importlib.util
import sys
from pathlib import Path

import torch

P2_DIR = Path(__file__).resolve().parents[2] / "malayalam-gpt"
P2_RUN = P2_DIR / "outputs" / "char"          # the 5000-step char model (best val loss 1.4976)
P2_CORPUS = P2_DIR / "data" / "corpus.txt"   # generated by P2's prepare_data.py, not committed


def _load_p2_package():
    if "p2" in sys.modules:
        return sys.modules["p2"]
    spec = importlib.util.spec_from_file_location(
        "p2", P2_DIR / "src" / "__init__.py", submodule_search_locations=[str(P2_DIR / "src")]
    )
    pkg = importlib.util.module_from_spec(spec)
    sys.modules["p2"] = pkg
    spec.loader.exec_module(pkg)
    return pkg


_load_p2_package()
p2_config = importlib.import_module("p2.config")
p2_model = importlib.import_module("p2.model")
p2_tokenizer = importlib.import_module("p2.tokenizer")
p2_data = importlib.import_module("p2.data")

GPT = p2_model.GPT
Config = p2_config.Config
count_params = p2_model.count_params


def load_tokenizer(run_dir: Path = P2_RUN):
    return p2_tokenizer.CharTokenizer.load(run_dir / "vocab.json")


def load_fp32_model(run_dir: Path = P2_RUN):
    """The trained P2 GPT on CPU in eval mode (dropout off), plus its config and checkpoint info."""
    ckpt = torch.load(run_dir / "model.pt", map_location="cpu")
    assert ckpt["tokenizer"] == "char", "this project quantizes the char model"
    cfg = Config(**ckpt["config"])
    model = GPT(cfg, load_tokenizer(run_dir).vocab_size)
    model.load_state_dict(ckpt["model"])
    model.eval()
    info = {"step": ckpt["step"], "val_loss": ckpt["val_loss"]}
    return model, cfg, info


def load_splits(tok=None):
    """P2's exact split: encode the whole corpus, first 90% train, last 10% val."""
    if not P2_CORPUS.exists():
        raise FileNotFoundError(
            f"{P2_CORPUS} is missing; run P2's scripts/download_data.py and scripts/prepare_data.py first"
        )
    tok = tok or load_tokenizer()
    data = torch.tensor(tok.encode(p2_data.load_corpus(P2_CORPUS)), dtype=torch.long)
    return p2_data.train_val_split(data)
